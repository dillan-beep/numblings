// Overwrite a run of characters starting at (x, y). Returns a new frame.
export function patch(frame, edits) {
  const rows = frame.map((r) => r.split(''));
  for (const [x, y, str] of edits) {
    for (let i = 0; i < str.length; i++) rows[y][x + i] = str[i];
  }
  return rows.map((r) => r.join(''));
}

// Shift a frame up 1px (drop the top margin row, add a transparent row at the bottom).
export function bob(frame) {
  const blank = '.'.repeat(frame[0].length);
  return [...frame.slice(1), blank];
}

const sprite = (frames, palette) => {
  const s = { w: frames[0][0].length, h: frames[0].length, frames };
  if (palette) s.palette = palette;
  return s;
};

